#!/usr/bin/env bash
# reqflow_session_init.sh
# SessionStart Hook：会话开始强制加载需求流程框架
#
# 机制：hook 不能"命令 AI 去读文件"，但能把内容直接注入 AI 上下文。
#       本 hook 在每个会话开始时，把 requirement-pipeline 的核心流程框架
#       注入 AI 上下文，确保 AI 全会话都"知道"流程存在、入口、阶段与强制规则。
#       这是"强制看内容"，不是"强制走流程"——非需求会话 AI 不主动启动流程。
#
# 注入的是核心摘要（非全文），AI 需要细节（闸门逐项/日志模板等）时
#       按 summary 末尾的路径去读完整 SKILL.md。

cat <<'EOF'
=== 需求流程框架（会话开始加载，供你了解全貌）===

【入口】
requirement-pipeline 是唯一总控。所有新需求 / 功能构想 / 设计变更，必须先经过它，不允许直接跳到子 skill 或直接写产物。

【启动确认（路径三要素 + 流程选择）】
流程启动时必须先与用户确认四件事，拼出方案根路径 个人/{作者}/{模块}/[功能名]/：
- 作者（必填）：命名标准「中文名-工号」，如 张三-1001
- 模块（可选）：七大模块之一，不归属具体模块时用 _通用 兜底（禁止自创）
- 功能名（必填）
  - 流程选择（必填）：A 资深跳诘问 / B 完整诘问（A/B 只影响阶段 0，阶段 1-5 相同）
后续所有 skill 产物的落盘路径都以方案根为基础（六类产物分别落到 RequirementAnalysis/VisualMockups/PRD/ReviewLogs/RequirementLogs/Retrospectives 子目录）。同一会话内同一功能不重复确认；回流沿用同一根路径。

【流程阶段】
阶段0 需求分析（requirement-analysis）：
  B 完整诘问：苏格拉底诘问 + 举证制 + 痛点深挖（四层：去伪→归因→痛点深挖→必要性），回答"要不要做、为什么做"
  A 资深跳诘问：自然描述→AI 提炼根源动机+痛点→用户确认→落盘标注"A·资深自述"
  产物落 个人/{作者}/{模块}/[功能名]/RequirementAnalysis/
    ↓ 论证通过 / 强制通过 / A·资深自述
阶段1 需求推演（brainstorming）：探索 2-3 种方案 + 取舍，回答"怎么做"。接收阶段0的根源动机+痛点画像作为约束基准。先读 team/project-context/ 建立产品认知
    ↓ 用户批准设计
阶段2 需求可视化（visual-companion）：生成 HTML 草图，用户预览改版。每次迭代后提醒"可复盘"。用户确认通过后提议 ui-spec-review（选配，审 UI 规范合理性）
    ↓ 用户确认通过
阶段3 PRD 生成（prd-generator）：纯产品文档（策划区 §0 需求与产品概述 / §1 设计取舍 / §2 假设风险；开发区 §3 功能设计 / §4 跨端差异 / §5 数据埋点（可选）；§6 更新记录）。产物落 个人/{作者}/{模块}/[功能名]/PRD/
    ↓
阶段4 需求评审（requirement-review）：三个评审员（完整性与逻辑 / 需求风险 / 用户体验）并行评审，评审输入含 PRD + 需求论证文档
    ↓ 用户确认
    ├─ 需修改 → 回阶段1（回流）：清理该功能的 .finalized 标记，提议增量复盘
    └─ 通过 → 阶段5
阶段5 需求复盘（retrospective）：可选。增量复盘（阶段0诘问(B) / 推演选型 / 可视化大推翻 / PRD审阅改稿 / 评审回流）+ 总复盘。产物落 个人/{作者}/{模块}/[功能名]/Retrospectives/
    ↓
定稿：创建 个人/{作者}/{模块}/[功能名]/RequirementLogs/.finalized 标记，流程闭环
（注意：定稿 ≠ 归档。归档到 team/finalized-proposals/ 需线下评审 + 人工审批，是 本流程之外的独立动作，本流程不自动触发）

【必记规则】
1. 我是唯一流程入口——所有新需求先经过 requirement-pipeline，不直接跳子 skill
2. 先论证再推演——新需求先走阶段0（要不要做），才能进阶段1（怎么做）
3. 先推演再出文档——必须经过推演 + 可视化确认，才能生成 PRD
4. 所有修改走完整流程——评审后任何 PRD 修改必须回阶段1重新走，不允许直接编辑 PRD
5. 禁止跳步——AI 不得以"改动小"为由跳过强制步骤，跳步唯一合法来源是用户明确授权
6. 定稿不自动归档——归档需人工审批，本流程绝不自动复制到 team/finalized-proposals/

【强制检查点】
- 防不论证直接推演：新需求必先经阶段0（无例外）
- 防无推演直接出文档：必先经 brainstorming 批准才能生成 PRD
- 防跳过可视化：推演批准后必经 visual-companion
- 防跳过评审：PRD 生成后必经 requirement-review
- 防直接编辑 PRD：修改必回阶段1，不允许直接改 PRD 文件
- 防自作主张定稿：定稿 / 回流必须用户明确确认
- 防自作主张归档：定稿标记 .finalized 不触发归档，归档必须经人工审批

【增量复盘】（防上下文压缩丢失）
关键转折点自动提议增量复盘：阶段0诘问后(B模式) / 推演选型/砍需求后 / 可视化大推翻后 / PRD初稿审阅改稿时 / 评审回流后。同一功能的复盘只一份文档，多次复盘追加章节。总复盘先读已有增量章节作为主力源。

【产物路径】
方案根 = 个人/{作者}/{模块}/[功能名]/，六类产物分别落到方案根下：
个人/{作者}/{模块}/[功能名]/RequirementAnalysis/（需求论证）
个人/{作者}/{模块}/[功能名]/VisualMockups/（可视化 HTML）
个人/{作者}/{模块}/[功能名]/PRD/（需求文档）
个人/{作者}/{模块}/[功能名]/ReviewLogs/（评审记录）
个人/{作者}/{模块}/[功能名]/RequirementLogs/（流程日志 + .finalized 标记）
个人/{作者}/{模块}/[功能名]/Retrospectives/（复盘总结）
项目背景（共享只读）：team/project-context/

完整流程细节（各阶段闸门逐项、流程日志模板、回流管理细则等）见：
.claude/skills/requirement-pipeline/SKILL.md

=== 当用户提出新需求 / 功能 / 改版时，按此流程执行；非需求会话不主动启动流程 ===
EOF

exit 0
